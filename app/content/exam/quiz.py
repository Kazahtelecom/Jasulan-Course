def evaluate_exam_quiz(answers: dict[str, int]) -> dict[str, Any]:
    """Evaluate final exam quiz answers.

    20 questions x 1.0 point = 20.0 max score. Pass threshold = 12.0 points.
    """
    correct_count = 0
    results: list[dict[str, Any]] = []

    for q in EXAM_QUIZ_QUESTIONS:
        qid = q["id"]
        selected = answers.get(qid)
        is_correct = selected is not None and int(selected) == q["correct_index"]
        if is_correct:
            correct_count += 1
        results.append(
            {
                "id": qid,
                "number": q["number"],
                "topic": q.get("topic", ""),
                "week": q.get("week", 1),
                "selected_index": selected,
                "correct_index": q["correct_index"],
                "is_correct": is_correct,
                "explanation": q["explanation"],
            }
        )

    score = round(float(correct_count) * POINTS_PER_QUESTION, 1)
    is_passed = score >= PASS_THRESHOLD

    return {
        "correct_count": correct_count,
        "total_questions": len(EXAM_QUIZ_QUESTIONS),
        "points_per_question": POINTS_PER_QUESTION,
        "score": score,
        "max_score": EXAM_QUIZ_MAX_SCORE,
        "pass_threshold": PASS_THRESHOLD,
        "is_passed": is_passed,
        "results": results,
    }
