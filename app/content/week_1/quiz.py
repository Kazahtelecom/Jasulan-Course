def evaluate_quiz(answers: dict[str, int]) -> dict[str, Any]:
    """Evaluate student quiz answers: 10 questions x 2.0 points = 20.0 max score."""
    correct_count = 0
    results: list[dict[str, Any]] = []

    for q in QUIZ_QUESTIONS:
        qid = q["id"]
        selected = answers.get(qid)
        is_correct = selected is not None and int(selected) == q["correct_index"]
        if is_correct:
            correct_count += 1
        results.append(
            {
                "id": qid,
                "number": q["number"],
                "selected_index": selected,
                "correct_index": q["correct_index"],
                "is_correct": is_correct,
                "explanation": q["explanation"],
            }
        )

    score = round(float(correct_count) * POINTS_PER_QUESTION, 1)
    return {
        "correct_count": correct_count,
        "total_questions": len(QUIZ_QUESTIONS),
        "points_per_question": POINTS_PER_QUESTION,
        "score": score,
        "max_score": QUIZ_MAX_SCORE,
        "results": results,
    }
