def check_quiz_answers(answers: dict[str, int]) -> dict:
    """Validate submitted answers, compute score, and produce pedagogical feedback.

    Max score: 3.0 points.
    Formula: round((correct / total) * 3.0, 1)
    """
    total_questions = len(QUIZ_QUESTIONS)
    correct_count = 0
    feedback_details = {}

    for question in QUIZ_QUESTIONS:
        qid = question["id"]
        selected = answers.get(qid)
        correct_idx = question["correct_option"]
        is_correct = selected == correct_idx

        if is_correct:
            correct_count += 1

        selected_explanation = ""
        if selected is not None and selected in question["explanations"]:
            selected_explanation = question["explanations"][selected]
        elif selected is None:
            selected_explanation = "Ответ на данный вопрос не был выбран."

        feedback_details[qid] = {
            "selected_option": selected,
            "correct_option": correct_idx,
            "is_correct": is_correct,
            "explanation": selected_explanation,
            "correct_explanation": question["explanations"][correct_idx],
        }

    raw_score = (correct_count / total_questions) * 3.0 if total_questions > 0 else 0.0
    final_score = round(raw_score, 1)

    return {
        "score": final_score,
        "max_score": 3.0,
        "correct_count": correct_count,
        "total_questions": total_questions,
        "details": feedback_details,
    }
